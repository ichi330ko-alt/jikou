window.getFlowerCycleData = function getFlowerCycleData(axis, cycle) {
  const key = window.FLOWER_DATA?.[axis]
    ? axis
    : window.RESONANCE_NAME_TO_KEY?.[axis];
  const cycleNumber = Number(cycle);
  const data = key ? window.FLOWER_DATA[key] : null;
  if (!data || ![1, 2, 3].includes(cycleNumber)) return null;
  return Object.freeze({
    key,
    cycle: cycleNumber,
    flower: data.flower[cycleNumber],
    movement: data.movement[cycleNumber]
  });
};
