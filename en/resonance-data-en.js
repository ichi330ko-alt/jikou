/**

 * 一文字キーまたは正式名称から、座データを取得します。

 *

 * @param {string} axis 一文字キー、または正式名称

 * @returns {object|null}

 */

window.getResonanceAxisDataEN = function getResonanceAxisDataEN(axis) {

  const key = window.RESONANCE_DATA_EN[axis]

    ? axis

    : window.RESONANCE_NAME_TO_KEY_EN[axis];

 

  return key ? window.RESONANCE_DATA_EN[key] : null;

};

 

 

/**

 * 一文字キーまたは正式名称と巡数から、表示用データを取得します。

 *

 * @param {string} axis 一文字キー、または正式名称

 * @param {number|string} cycle 1、2、3のいずれか

 * @returns {{

 *   key: string,

 *   name: string,

 *   image: string,

 *   cycle: number,

 *   symbolName: string,

 *   romaji: string,

 *   text: string

 * }|null}

 */

window.getResonanceCycleDataEN = function getResonanceCycleDataEN(axis, cycle) {

  const axisData = window.getResonanceAxisDataEN(axis);

  const cycleNumber = Number(cycle);

 

  if (!axisData || !axisData.cycles[cycleNumber]) {

    return null;

  }

 

  const cycleData = axisData.cycles[cycleNumber];

 

  return {

    key: axisData.key,

    name: axisData.name,

    image: axisData.image,

    cycle: cycleData.cycle,

    symbolName: cycleData.symbolName,

    romaji: cycleData.romaji,

    text: cycleData.text

  };

};
